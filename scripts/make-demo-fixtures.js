#!/usr/bin/env node
/**
 * Generate the synthetic fixtures the mock backend replays.
 *
 * Only DELIVERY had one, so every other business object could only be
 * demonstrated against a live iFlow — which needs CPI credentials, a reachable
 * Integration Suite tenant and a working S/4 connection. That is three things
 * that can fail in front of an audience.
 *
 * These are GENERATED, not captured. The field names follow the S/4 OData
 * services so the same question works unchanged against a real backend, but no
 * value here came from a customer system or an SAP sandbox.
 *
 * Deterministic on purpose: no Math.random, so regenerating produces the same
 * file and a diff means someone changed the generator.
 */

const fs = require('node:fs')
const path = require('node:path')

const ROOT = path.join(__dirname, '..', 'docs', 'api', 'hub')
const BASE_DATE = '2026-08-19' // MockBackend shifts these forward so "today" keeps working

/** Cheap deterministic PRNG — same sequence every run. */
function rng(seed) {
  let s = seed
  return () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff)
}

const PLANTS = ['1000', '1010', '2000']
const WAREHOUSES = ['1000', '1010', '2000']
const MATERIALS = [
  { id: 'P123', text: 'Hydraulic Pump Assembly', uom: 'EA' },
  { id: 'P456', text: 'Steel Bearing 40mm', uom: 'EA' },
  { id: 'P789', text: 'Conveyor Belt 2m', uom: 'M' },
  { id: 'RM100', text: 'Cold Rolled Steel Sheet', uom: 'KG' },
  { id: 'RM200', text: 'Industrial Lubricant', uom: 'L' },
  { id: 'FG500', text: 'Gearbox Unit GX-500', uom: 'EA' },
]
const SUPPLIERS = [
  { id: '100001', name: 'Bergmann Industrieteile GmbH' },
  { id: '100002', name: 'Nordic Steel AB' },
  { id: '100003', name: 'Precision Components Ltd' },
]

const day = (base, offset) => {
  const d = new Date(`${base}T00:00:00Z`)
  d.setUTCDate(d.getUTCDate() + offset)
  return d.toISOString().slice(0, 10)
}
/** S/4 OData v2 serialises dates as /Date(ms)/. Keeping that shape means the
 *  date handling in backend.js is exercised by the mock, not bypassed. */
const odataDate = (iso) => `/Date(${new Date(`${iso}T00:00:00Z`).getTime()})/`

function write(dir, entitySet, service, rows, extra = {}) {
  const target = path.join(ROOT, dir)
  fs.mkdirSync(target, { recursive: true })
  const body = {
    _synthetic: {
      warning:
        'SYNTHETIC DATA — generated by scripts/make-demo-fixtures.js for offline demo and development. ' +
        'This is NOT a capture from a real SAP system, customer tenant, or Business Accelerator Hub Try Out. ' +
        'Field names follow the S/4 OData service so the same question works against a real backend unchanged.',
      generator: 'scripts/make-demo-fixtures.js',
      baseDate: BASE_DATE,
      entitySet,
      service,
      rowCount: rows.length,
      ...extra,
    },
    d: { results: rows },
  }
  const file = path.join(target, 'sample_response.synthetic.json')
  fs.writeFileSync(file, JSON.stringify(body, null, 2) + '\n')
  console.log(`  ${path.relative(process.cwd(), file)} — ${rows.length} rows`)
}

// --- Material stock ----------------------------------------------------------
// One row per material/plant/storage-location, the way A_MatlStkInAcctMod is
// actually shaped. A believable stock question needs unrestricted, blocked and
// quality-inspection quantities to differ.
function materialStock() {
  const r = rng(11)
  const rows = []
  // Field names mirror A_MatlStkInAcctMod as the live Hub returns it: a single
  // MatlWrhsStkQtyInMatlBaseUnit per row, with InventoryStockType saying what
  // kind of stock it is. 01 unrestricted, 02 quality inspection, 03 blocked.
  for (const m of MATERIALS) {
    for (const plant of PLANTS) {
      for (const [type, share] of [['01', 1], ['02', 0.06], ['03', 0.04]]) {
        const qty = Math.round((r() * 900 + 20) * share)
        if (!qty) continue
        rows.push({
          __metadata: { type: 'API_MATERIAL_STOCK_SRV.A_MatlStkInAcctModType' },
          Material: m.id,
          Plant: plant,
          StorageLocation: r() > 0.5 ? '0001' : '0002',
          Batch: '',
          InventoryStockType: type,
          InventorySpecialStockType: '',
          MaterialBaseUnit: m.uom,
          MatlWrhsStkQtyInMatlBaseUnit: String(qty) + '.000',
        })
      }
    }
  }
  write('material_stock', 'A_MatlStkInAcctMod', 'API_MATERIAL_STOCK_SRV', rows)
}

// --- Material documents (goods movements) ------------------------------------
function materialDocuments() {
  const r = rng(23)
  const rows = []
  const types = ['101', '261', '311', '601']
  for (let i = 0; i < 60; i++) {
    const m = MATERIALS[Math.floor(r() * MATERIALS.length)]
    const movement = types[Math.floor(r() * types.length)]
    const cancelled = r() > 0.92
    rows.push({
      __metadata: { type: 'API_MATERIAL_DOCUMENT_SRV.A_MaterialDocumentItemType' },
      MaterialDocument: String(4900000000 + i),
      MaterialDocumentYear: BASE_DATE.slice(0, 4),
      MaterialDocumentItem: '0001',
      Material: m.id,
      Plant: PLANTS[Math.floor(r() * PLANTS.length)],
      StorageLocation: r() > 0.5 ? '0001' : '0002',
      GoodsMovementType: movement,
      QuantityInEntryUnit: String(Math.round(r() * 250) + 5),
      EntryUnit: m.uom,
      // A reversal is recorded on the item that reverses it, so a net figure
      // that ignores this double-counts.
      ReversedMaterialDocument: cancelled ? String(4900000000 + i - 1) : '',
      GoodsMovementIsCancelled: cancelled,
    })
  }
  write('material_document', 'A_MaterialDocumentItem', 'API_MATERIAL_DOCUMENT_SRV', rows)
}

// --- Physical inventory ------------------------------------------------------
function physicalInventory() {
  const r = rng(37)
  const rows = []
  for (let i = 0; i < 24; i++) {
    const counted = r() > 0.35
    const offset = -Math.floor(r() * 14)
    rows.push({
      __metadata: { type: 'API_PHYSICAL_INVENTORY_DOC_SRV.A_PhysInventoryDocHeaderType' },
      FiscalYear: BASE_DATE.slice(0, 4),
      PhysicalInventoryDocument: String(100000000 + i),
      InventoryTransactionType: 'IB',
      Plant: PLANTS[Math.floor(r() * PLANTS.length)],
      StorageLocation: r() > 0.5 ? '0001' : '0002',
      InventorySpecialStockType: '',
      DocumentDate: odataDate(day(BASE_DATE, offset)),
      PhysInventoryPlannedCountDate: odataDate(day(BASE_DATE, offset + 2)),
      PhysicalInventoryLastCountDate: counted ? odataDate(day(BASE_DATE, offset + 2)) : null,
      PostingDate: odataDate(day(BASE_DATE, offset)),
      // 'X' means done; empty means outstanding. Same convention as S/4.
      PhysicalInventoryCountStatus: counted ? 'X' : '',
      PhysInvtryAdjustmentPostingSts: counted && r() > 0.4 ? 'X' : '',
      PhysInvtryDeletionStatus: '',
    })
  }
  write('physical_inventory', 'A_PhysInventoryDocHeader', 'API_PHYSICAL_INVENTORY_DOC_SRV', rows)
}

// --- Purchase orders ---------------------------------------------------------
function purchaseOrders() {
  const r = rng(53)
  const rows = []
  for (let i = 0; i < 40; i++) {
    const s = SUPPLIERS[Math.floor(r() * SUPPLIERS.length)]
    const offset = -Math.floor(r() * 21)
    rows.push({
      __metadata: { type: 'API_PURCHASEORDER_PROCESS_SRV.A_PurchaseOrderType' },
      PurchaseOrder: String(4500000000 + i),
      PurchaseOrderType: 'NB',
      PurchaseOrderDate: odataDate(day(BASE_DATE, offset)),
      Supplier: s.id,
      PurchasingOrganization: '1010',
      PurchasingGroup: r() > 0.5 ? '001' : '002',
      CompanyCode: '1010',
      DocumentCurrency: 'EUR',
      PurchasingProcessingStatus: r() > 0.55 ? '02' : '01',
      // Empty means still open; 'X' means complete.
      PurchasingCompletenessStatus: r() > 0.55 ? 'X' : '',
      PurchasingDocumentDeletionCode: r() > 0.95 ? 'L' : '',
    })
  }
  write('purchasing', 'A_PurchaseOrder', 'API_PURCHASEORDER_PROCESS_SRV', rows)
}

console.log('Generating synthetic fixtures (deterministic — no random seed):')
materialStock()
materialDocuments()
physicalInventory()
purchaseOrders()
console.log('Done. These are generated, not captured — see the _synthetic block in each file.')
